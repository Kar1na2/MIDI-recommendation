"""Check generated-cache cleanup after the full end-of-run hash audit.

This complements, and does not overwrite, integrity_end.json. It rescans the
round-one file inventory after removing the two newly generated bytecode files;
it does not rehash the snapshot-listed files, which were checked by the full
audit immediately before cleanup.
"""
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
if sys.executable != '/home/usr/venvs/midi/bin/python':
    raise RuntimeError('Wrong interpreter')

HERE = Path(__file__).resolve().parent
R1 = HERE.parent / 'emotion'
EXCLUDED = {'private', 'model_cache', 'stems'}

baseline = json.loads((HERE / 'r1_snapshot.json').read_text(encoding='utf-8'))['files']
audit = json.loads((HERE / 'integrity_end.json').read_text(encoding='utf-8'))
inventory = {p.relative_to(R1).as_posix() for p in R1.rglob('*')
             if p.is_file() and p.relative_to(R1).parts[0] not in EXCLUDED}
missing = sorted(set(baseline) - inventory)
extra = sorted(inventory - set(baseline))
result = {
    'source_full_hash_audit': 'integrity_end.json',
    'full_hash_audit_note': 'Snapshot-listed files were hashed before cleanup; this inventory rescan does not rehash them.',
    'round1_hashed_unchanged': audit['round1']['unchanged'],
    'round1_hashed_total': audit['round1']['total'],
    'round1_inventory_missing_after_cleanup': missing,
    'round1_inventory_extra_after_cleanup': extra,
    'v1_hashed_unchanged': audit['v1']['unchanged'],
    'v1_hashed_total': audit['v1']['total'],
    'mvp_325_hashed_unchanged': audit['mvp_325']['unchanged'],
    'mvp_325_hashed_total': audit['mvp_325']['total'],
}
result['passed'] = (audit['round1']['unchanged'] == audit['round1']['total']
                    and audit['v1']['passed'] and audit['mvp_325']['passed']
                    and not missing and not extra)
(HERE / 'integrity_post_cleanup.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
print(json.dumps(result, indent=2))
raise SystemExit(0 if result['passed'] else 1)
